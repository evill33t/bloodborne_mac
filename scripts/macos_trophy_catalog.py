"""Generate the C catalog from the shared Bloodborne trophy list."""
import importlib.util
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent


def render():
    source = ROOT / "scripts/trophies.py"
    spec = importlib.util.spec_from_file_location("bb_trophy_catalog", source)
    catalog = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(catalog)
    grades = {grade: index + 1 for index, grade in enumerate(catalog.GRADES)}
    text = (
        "/* SPDX-License-Identifier: GPL-2.0-or-later\n"
        " * Generated by scripts/macos_trophy_catalog.py from scripts/trophies.py,\n"
        " * shared with pyL1nx/bloodborne_pc at 64919f7da13a24bac53578acec5f74f959fe5c4e.\n"
        " */\n"
    )
    for trophy, name, description, grade, group in catalog.TROPHIES:
        text += (
            f"{{{trophy},{grades[grade]},{int(group == catalog.DLC)},"
            f"{json.dumps(name, ensure_ascii=False)},{json.dumps(description, ensure_ascii=False)}}},\n"
        )
    return text


if __name__ == "__main__":
    output = ROOT / "src/bloodborne_trophies.inc"
    expected = render()
    if "--check" in sys.argv:
        if output.read_text() != expected:
            sys.exit("C achievement catalog is stale; run scripts/macos_trophy_catalog.py")
    else:
        output.write_text(expected)
